def _merge_imprint_batches(*batches: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    merged: Dict[str, Dict[str, Any]] = {}
    for batch in batches:
        for raw_entry in batch:
            key = str(raw_entry.get("key") or "").strip()
            if not key:
                continue
            previous = merged.pop(key, {})
            entry = {**previous, **raw_entry}
            if "tags" not in raw_entry:
                previous_tags = previous.get("tags")
                if isinstance(previous_tags, list):
                    entry["tags"] = list(previous_tags)
            entry.setdefault("tags", [])
            merged[key] = entry
    return list(merged.values())

