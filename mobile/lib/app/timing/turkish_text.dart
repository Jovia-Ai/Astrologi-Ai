String normalizeTurkishText(String value) {
  var out = value.replaceAll('\r', ' ').replaceAll('\n', ' ');
  out = out.replaceAll(RegExp(r'\s+'), ' ').trim();
  if (out.isEmpty) {
    return '';
  }

  for (final entry in _turkishWordFixes.entries) {
    out = out.replaceAllMapped(
      RegExp(r'\b' + RegExp.escape(entry.key) + r'\b', caseSensitive: false),
      (match) => _matchCase(match.group(0) ?? '', entry.value),
    );
  }

  out = out.replaceAllMapped(
    RegExp(r'\b([1-9]|1[0-2])\s*ev\b', caseSensitive: false),
    (match) => '${match.group(1)}. Ev',
  );
  out = out.replaceAllMapped(
    RegExp(r'\b([1-9]|1[0-2])\.\s*ev\b', caseSensitive: false),
    (match) => '${match.group(1)}. Ev',
  );

  return out.replaceAll(RegExp(r'\s+'), ' ').trim();
}

List<String> normalizeTurkishTextList(Iterable<dynamic> values) {
  return values
      .map((item) => normalizeTurkishText(item.toString().trim()))
      .where((item) => item.isNotEmpty)
      .toList(growable: false);
}

String turkishToUpper(String value) {
  if (value.isEmpty) {
    return value;
  }
  return _toTurkishUpper(value);
}

String turkishCapitalize(String value) {
  final normalized = normalizeTurkishText(value);
  if (normalized.isEmpty) {
    return normalized;
  }
  return _capitalizeTurkish(normalized.substring(0, 1)) +
      normalized.substring(1);
}

String _matchCase(String source, String replacement) {
  if (source.isEmpty) {
    return replacement;
  }
  if (source == source.toUpperCase()) {
    return _toTurkishUpper(replacement);
  }
  final first = source.substring(0, 1);
  if (first == first.toUpperCase()) {
    return _capitalizeTurkish(replacement);
  }
  return replacement;
}

String _capitalizeTurkish(String value) {
  if (value.isEmpty) {
    return value;
  }
  return _toTurkishUpper(value.substring(0, 1)) + value.substring(1);
}

String _toTurkishUpper(String value) {
  final buffer = StringBuffer();
  for (final rune in value.runes) {
    final char = String.fromCharCode(rune);
    switch (char) {
      case 'i':
        buffer.write('İ');
        break;
      case 'ı':
        buffer.write('I');
        break;
      case 'ğ':
        buffer.write('Ğ');
        break;
      case 'ü':
        buffer.write('Ü');
        break;
      case 'ş':
        buffer.write('Ş');
        break;
      case 'ö':
        buffer.write('Ö');
        break;
      case 'ç':
        buffer.write('Ç');
        break;
      default:
        buffer.write(char.toUpperCase());
        break;
    }
  }
  return buffer.toString();
}
